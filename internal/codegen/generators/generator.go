package generators

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"

	"github.com/lanceman/zqk/pkg/errfmt"
)

// FieldDefinition specifies a struct field for code generation.
type FieldDefinition struct {
	Name     string
	Type     string
	JSONTag  string
	YAMLTag  string
	Comment  string
	Required bool
}

// EntitySpec defines the parameters for generating a cellular domain entity.
type EntitySpec struct {
	PackageName     string
	EntityName      string
	Kind            string
	SchemaRef       string
	IncludeAudit    bool
	IncludeLifecycle bool
	Fields          []FieldDefinition
}

// EntityGenerator synthesizes cellular entity code conforming strictly to BaseObject and MetaSchema.
type EntityGenerator struct{}

// NewEntityGenerator creates a new EntityGenerator instance.
func NewEntityGenerator() *EntityGenerator {
	return &EntityGenerator{}
}

// GenerateEntityCode emits formatted Go source code conforming to cellular microkernel primitives.
func (eg *EntityGenerator) GenerateEntityCode(spec EntitySpec) ([]byte, error) {
	if strings.TrimSpace(spec.PackageName) == "" {
		return nil, errfmt.Errorf("package name is required")
	}
	if strings.TrimSpace(spec.EntityName) == "" {
		return nil, errfmt.Errorf("entity name is required")
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by zqk codegen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", spec.PackageName)
	buf.WriteString("import (\n")
	buf.WriteString("\t\"github.com/lanceman/zqk/pkg/dna\"\n")
	buf.WriteString(")\n\n")

	// Struct definition
	fmt.Fprintf(&buf, "// %s represents a cellular %s object.\n", spec.EntityName, spec.Kind)
	fmt.Fprintf(&buf, "type %s struct {\n", spec.EntityName)
	buf.WriteString("\tdna.BaseObject `yaml:\",inline\" json:\",inline\"`\n")
	if spec.IncludeAudit {
		buf.WriteString("\tdna.Auditable  `yaml:\",inline\" json:\",inline\"`\n")
	}
	if spec.IncludeLifecycle {
		buf.WriteString("\tdna.Lifecycle  `yaml:\",inline\" json:\",inline\"`\n")
	}

	for _, f := range spec.Fields {
		jsonTag := f.JSONTag
		if jsonTag == "" {
			jsonTag = strings.ToLower(f.Name)
		}
		yamlTag := f.YAMLTag
		if yamlTag == "" {
			yamlTag = jsonTag
		}
		if f.Comment != "" {
			fmt.Fprintf(&buf, "\t// %s\n", f.Comment)
		}
		fmt.Fprintf(&buf, "\t%s %s `json:\"%s\" yaml:\"%s\"`\n", f.Name, f.Type, jsonTag, yamlTag)
	}
	buf.WriteString("}\n\n")

	// Constructor
	constructorName := "New" + spec.EntityName
	fmt.Fprintf(&buf, "// %s constructs a new %s initialized with BaseObject.\n", constructorName, spec.EntityName)
	fmt.Fprintf(&buf, "func %s(id string) (*%s, error) {\n", constructorName, spec.EntityName)
	fmt.Fprintf(&buf, "\turn, err := dna.NewURN(%q, %q, id)\n", spec.PackageName, spec.Kind)
	buf.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	schemaRef := spec.SchemaRef
	if schemaRef == "" {
		schemaRef = "1.0.0"
	}
	fmt.Fprintf(&buf, "\tbase := dna.NewBaseObject(urn, %q)\n", schemaRef)
	fmt.Fprintf(&buf, "\treturn &%s{\n\t\tBaseObject: base,\n\t}, nil\n}\n", spec.EntityName)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, errfmt.Errorf("failed to format generated source code: %w\n%s", err, buf.String())
	}

	return formatted, nil
}
