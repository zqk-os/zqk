func TestCommon_ExemptionsAndGenerated(t *testing.T) {
	// isGeneratedCode
	genHeader := []byte("// Code generated by tool. DO NOT EDIT.\npackage foo")
	assert.True(t, isGeneratedCode(genHeader))

	nonGenHeader := []byte("// Package foo does something.\npackage foo")
	assert.False(t, isGeneratedCode(nonGenHeader))

	// isPathExempt
	exemptions := []string{"pkg/generated/*", "vendor/", "docs/spec.md"}
	assert.True(t, isPathExempt("pkg/generated/builder.go", exemptions))
	assert.True(t, isPathExempt("vendor/foo/bar.go", exemptions))
	assert.True(t, isPathExempt("docs/spec.md", exemptions))
	assert.False(t, isPathExempt("pkg/real/code.go", exemptions))

	// matchesScanDirs
	scanDirs := []string{"pkg", "cmd"}
	assert.True(t, matchesScanDirs("pkg/vet/runner.go", scanDirs))
	assert.True(t, matchesScanDirs("cmd/zqk/main.go", scanDirs))
	assert.False(t, matchesScanDirs("docs/readme.md", scanDirs))

	// collectGitFiles on current repo
	files, err := collectGitFiles("../..")
	assert.NoError(t, err)
	assert.NotEmpty(t, files)

	// collectGoFiles on pkg
	goFiles, err := collectGoFiles("../..", []string{"pkg"})
	assert.NoError(t, err)
	assert.NotEmpty(t, goFiles)
}

func TestCheckCLINames_ASTHelpers(t *testing.T) {
	// callFunName
	identCall := &ast.CallExpr{
		Fun: &ast.Ident{Name: "myFunc"},
	}
	assert.Equal(t, "myFunc", callFunName(identCall))

	selCall := &ast.CallExpr{
		Fun: &ast.SelectorExpr{
			Sel: &ast.Ident{Name: "myMethod"},
		},
	}
	assert.Equal(t, "myMethod", callFunName(selCall))

	badCall := &ast.CallExpr{
		Fun: &ast.BasicLit{},
	}
	assert.Empty(t, callFunName(badCall))

	// inConstDecl
	constStack := []ast.Node{
		&ast.GenDecl{Tok: token.CONST},
		&ast.ValueSpec{},
	}
	assert.True(t, inConstDecl(constStack))

	varStack := []ast.Node{
		&ast.GenDecl{Tok: token.VAR},
	}
	assert.False(t, inConstDecl(varStack))

	// callExempt
	exemptStack := []ast.Node{
		identCall,
	}
	assert.True(t, callExempt(exemptStack, map[string]struct{}{"myFunc": {}}))
	assert.False(t, callExempt(exemptStack, map[string]struct{}{"other": {}}))

	// firstCanonicalCLIHit with product verb
	hit, verb := firstCanonicalCLIHit("zqk object read")
	assert.True(t, hit)
	assert.Equal(t, "object", verb)

	hit, _ = firstCanonicalCLIHit("not a cli command")
	assert.False(t, hit)
}

func TestRunner_FullExecution(t *testing.T) {
	tempDir := t.TempDir()

	cfg := &GatesConfig{
		Hygiene: HygieneConfig{
			CheckPaths:    true,
			CheckPerms:    true,
			CheckCLINames: true,
			GoScanDirs:    []string{"pkg"},
		},
		TreePolice: TreePoliceConfig{
			ForbiddenPaths: []string{"bad_dir"},
		},
		Payload: PayloadConfig{
			RequiredArtifacts: []string{"README.md"},
		},
	}
	require.NoError(t, os.WriteFile(filepath.Join(tempDir, "README.md"), []byte("# OK"), 0644))

	// Create valid go file under pkg
	pkgDir := filepath.Join(tempDir, "pkg", "sample")
	require.NoError(t, os.MkdirAll(pkgDir, 0755))
	validGo := "package sample\n\nconst Greeting = \"hello\"\n"
	require.NoError(t, os.WriteFile(filepath.Join(pkgDir, "sample.go"), []byte(validGo), 0644))

	runner := NewRunner(tempDir, cfg)
	report, err := runner.Run(RunOptions{
		Suites: []string{"all"},
	})
	assert.NoError(t, err)
	assert.NotNil(t, report)

	var buf bytes.Buffer
	runner.PrintReport(&buf, report)
	assert.NotEmpty(t, buf.String())

	// Normalize suites
	normalized := runner.normalizeSuites(nil)
	assert.Equal(t, []string{"hygiene", "tree_police", "payload"}, normalized)
	normalizedAll := runner.normalizeSuites([]string{"all"})
	assert.Equal(t, []string{"hygiene", "tree_police", "payload"}, normalizedAll)
}

