func TestFinding_String(t *testing.T) {
	f1 := Finding{
		Severity: SeverityError,
		File:     "foo.go",
		Line:     42,
		Message:  "bad syntax",
		CheckID:  "check/1",
	}
	assert.Equal(t, "[ERROR] foo.go:42: bad syntax (check/1)", f1.String())

	f2 := Finding{
		Severity: SeverityWarn,
		File:     "bar.go",
		Message:  "check this",
		CheckID:  "check/2",
	}
	assert.Equal(t, "[WARN] bar.go: check this (check/2)", f2.String())

	f3 := Finding{
		Severity: SeverityError,
		Message:  "global failure",
		CheckID:  "check/3",
	}
	assert.Equal(t, "[ERROR] global failure (check/3)", f3.String())
}

