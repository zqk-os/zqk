package vet

import (
	"path/filepath"
	"strings"
	"testing"

	fileutil "github.com/zqk-os/zqk/pkg/utils/fileutil"
)

func TestCheckGoFormatting(t *testing.T) {
	tempDir := t.TempDir()

	// 1. Properly formatted Go file
	cleanDir := filepath.Join(tempDir, "pkg", "clean")
	if err := fileutil.MkdirAll(cleanDir, 0o755); err != nil {
		t.Fatalf("mkdir clean: %v", err)
	}
	cleanCode := `package clean

import "fmt"

func Hello() {
	fmt.Println("hello world")
}
`
	if err := fileutil.WriteFile(filepath.Join(cleanDir, "clean.go"), []byte(cleanCode), 0o644); err != nil {
		t.Fatalf("write clean.go: %v", err)
	}

	// 2. Unformatted Go file (formatting drift: extra spaces, bad indentation)
	unformattedDir := filepath.Join(tempDir, "pkg", "drift")
	if err := fileutil.MkdirAll(unformattedDir, 0o755); err != nil {
		t.Fatalf("mkdir drift: %v", err)
	}
	unformattedCode := `package   drift

import   "fmt"

func   BadFormatting(  )    {
fmt.Println( "drift" )
}
`
	if err := fileutil.WriteFile(filepath.Join(unformattedDir, "bad.go"), []byte(unformattedCode), 0o644); err != nil {
		t.Fatalf("write bad.go: %v", err)
	}

	// 3. Unformatted file in vendor/ (exempt)
	vendorDir := filepath.Join(tempDir, "vendor", "lib")
	if err := fileutil.MkdirAll(vendorDir, 0o755); err != nil {
		t.Fatalf("mkdir vendor: %v", err)
	}
	if err := fileutil.WriteFile(filepath.Join(vendorDir, "vendor.go"), []byte(unformattedCode), 0o644); err != nil {
		t.Fatalf("write vendor.go: %v", err)
	}

	// 4. Unformatted file in testdata/ (exempt)
	testdataDir := filepath.Join(cleanDir, "testdata")
	if err := fileutil.MkdirAll(testdataDir, 0o755); err != nil {
		t.Fatalf("mkdir testdata: %v", err)
	}
	if err := fileutil.WriteFile(filepath.Join(testdataDir, "fixture.go"), []byte(unformattedCode), 0o644); err != nil {
		t.Fatalf("write fixture.go: %v", err)
	}

	// 5. Generated code with formatting drift (exempt)
	generatedDir := filepath.Join(tempDir, "pkg", "generated")
	if err := fileutil.MkdirAll(generatedDir, 0o755); err != nil {
		t.Fatalf("mkdir generated: %v", err)
	}
	genCode := `// Code generated by test. DO NOT EDIT.
package generated

func   Gen(  ) {
fmt.Println("gen")
}
`
	if err := fileutil.WriteFile(filepath.Join(generatedDir, "gen.go"), []byte(genCode), 0o644); err != nil {
		t.Fatalf("write gen.go: %v", err)
	}

	// 6. Custom exempted file
	customExemptDir := filepath.Join(tempDir, "pkg", "custom")
	if err := fileutil.MkdirAll(customExemptDir, 0o755); err != nil {
		t.Fatalf("mkdir custom: %v", err)
	}
	if err := fileutil.WriteFile(filepath.Join(customExemptDir, "skip.go"), []byte(unformattedCode), 0o644); err != nil {
		t.Fatalf("write skip.go: %v", err)
	}

	cfg := DefaultConfig()
	cfg.Hygiene.GoScanDirs = []string{"pkg"}
	cfg.Hygiene.FormattingExemptions = []string{"vendor/*", "*/testdata/*", "pkg/custom/*"}

	findings, err := CheckGoFormatting(tempDir, nil, cfg)
	if err != nil {
		t.Fatalf("CheckGoFormatting failed: %v", err)
	}

	if len(findings) != 1 {
		t.Fatalf("expected exactly 1 finding, got %d: %+v", len(findings), findings)
	}

	f := findings[0]
	if f.CheckID != CheckIDFormatting {
		t.Errorf("expected CheckID '%s', got '%s'", CheckIDFormatting, f.CheckID)
	}
	if f.Severity != SeverityError {
		t.Errorf("expected SeverityError, got %s", f.Severity)
	}
	if f.File != "pkg/drift/bad.go" {
		t.Errorf("expected file 'pkg/drift/bad.go', got %s", f.File)
	}
	if !strings.Contains(f.Message, "formatting drift detected") {
		t.Errorf("unexpected message: %s", f.Message)
	}
}

func TestCheckGoFormatting_EdgeCases(t *testing.T) {
	tempDir := t.TempDir()

	// Non-existent file in explicit files list should be skipped gracefully
	findings, err := CheckGoFormatting(tempDir, []string{"pkg/nonexistent.go"}, nil)
	if err != nil {
		t.Fatalf("unexpected error for non-existent file: %v", err)
	}
	if len(findings) != 0 {
		t.Fatalf("expected 0 findings for non-existent file, got %d", len(findings))
	}

	// Non-go file should be ignored
	nonGoPath := filepath.Join(tempDir, "README.md")
	if err := fileutil.WriteFile(nonGoPath, []byte("# Hello\n"), 0o644); err != nil {
		t.Fatalf("write non-go: %v", err)
	}
	findings, err = CheckGoFormatting(tempDir, []string{"README.md"}, nil)
	if err != nil {
		t.Fatalf("unexpected error for non-go file: %v", err)
	}
	if len(findings) != 0 {
		t.Fatalf("expected 0 findings for non-go file, got %d", len(findings))
	}

	// Syntax error in Go file produces SeverityError finding
	syntaxErrDir := filepath.Join(tempDir, "pkg", "syntaxerr")
	if err := fileutil.MkdirAll(syntaxErrDir, 0o755); err != nil {
		t.Fatalf("mkdir syntaxerr: %v", err)
	}
	syntaxErrCode := `package syntaxerr

func Broken( {
`
	syntaxErrFile := filepath.Join(syntaxErrDir, "broken.go")
	if err := fileutil.WriteFile(syntaxErrFile, []byte(syntaxErrCode), 0o644); err != nil {
		t.Fatalf("write broken.go: %v", err)
	}

	findings, err = CheckGoFormatting(tempDir, []string{"pkg/syntaxerr/broken.go"}, nil)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(findings) != 1 {
		t.Fatalf("expected 1 finding for syntax error, got %d", len(findings))
	}
	if findings[0].Severity != SeverityError {
		t.Errorf("expected SeverityError, got %s", findings[0].Severity)
	}
	if !strings.Contains(findings[0].Message, "go format error") {
		t.Errorf("expected go format error message, got %s", findings[0].Message)
	}
}

func TestCheckGoFormatting_RunnerIntegration(t *testing.T) {
	tempDir := t.TempDir()
	pkgDir := filepath.Join(tempDir, "pkg", "example")
	if err := fileutil.MkdirAll(pkgDir, 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	unformatted := `package example
func   Foo()   {
}
`
	if err := fileutil.WriteFile(filepath.Join(pkgDir, "example.go"), []byte(unformatted), 0o644); err != nil {
		t.Fatalf("write example.go: %v", err)
	}

	cfg := DefaultConfig()
	cfg.Hygiene.GoScanDirs = []string{"pkg"}
	cfg.Hygiene.CheckPaths = false
	cfg.Hygiene.CheckPerms = false
	cfg.Hygiene.CheckCLINames = false
	cfg.Hygiene.CheckSubprocessHygiene = false
	cfg.Hygiene.CheckFileutilHygiene = false
	cfg.Hygiene.CheckCommandSpecs = false
	cfg.Hygiene.CheckCLIBuilders = false
	cfg.Hygiene.CheckRawGoroutines = false
	cfg.Hygiene.CheckReferenceIntegrity = false
	cfg.Hygiene.CheckDups = false
	cfg.Hygiene.CheckFormatting = true

	runner := NewRunner(tempDir, cfg)
	report, err := runner.Run(RunOptions{Suites: []string{"hygiene"}})
	if err != nil {
		t.Fatalf("runner.Run failed: %v", err)
	}
	if report.Passed {
		t.Fatalf("expected suite to fail due to unformatted file")
	}
	if report.TotalErrors != 1 {
		t.Fatalf("expected 1 error, got %d", report.TotalErrors)
	}
}

func TestCheckGoFormatting_RepoCompliance(t *testing.T) {
	cfg := DefaultConfig()
	findings, err := CheckGoFormatting("../..", nil, cfg)
	if err != nil {
		t.Fatalf("CheckGoFormatting on repo failed: %v", err)
	}
	if len(findings) > 0 {
		for _, f := range findings {
			t.Logf("drift in repo file: %s", f.String())
		}
		t.Errorf("repo contains %d unformatted files", len(findings))
	}
}
