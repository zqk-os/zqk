func TestAllCommandBuilders_InstantiateAndVerify(t *testing.T) {
	for _, tt := range allCommandBuilders {
		t.Run(tt.name, func(t *testing.T) {
			cmd := tt.fn()
			if cmd == nil {
				t.Fatalf("expected non-nil command for %s", tt.name)
			}
			if cmd.Flags() == nil {
				t.Errorf("command %s has nil flags", tt.name)
			}
			usage := cmd.UsageString()
			if usage == "" {
				t.Errorf("expected non-empty usage string for %s", tt.name)
			}
		})
	}
}
