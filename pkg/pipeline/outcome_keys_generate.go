package pipeline

import (
	"fmt"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/zqk-os/zqk/pkg/errfmt"
	"github.com/zqk-os/zqk/pkg/objects"
	"github.com/zqk-os/zqk/pkg/paths"
	fileutil "github.com/zqk-os/zqk/pkg/utils/fileutil"
)

// outcomeKeyConstSuffixOverrides map wire keys to Go identifier suffixes (after "OutcomeKey")
// when [objects.FieldKeyConstName] would not match established pipeline naming (e.g. …CSV).
var outcomeKeyConstSuffixOverrides = map[string]string{
	"output_csv": "OutputCSV",
}

func outcomeKeyConstSuffix(wireKey string) string {
	if s, ok := outcomeKeyConstSuffixOverrides[wireKey]; ok {
		return s
	}
	return objects.FieldKeyConstName(wireKey)
}

// pipelineOutcomeKeysYAML is the on-disk shape for .zqk/specs/pipeline_outcome_keys.yaml.
type pipelineOutcomeKeysYAML struct {
	SchemaVersion int      `yaml:"schema_version"`
	Keys          []string `yaml:"keys"`
}

// LoadOutcomeKeyNamesFromYAML reads and validates the pipeline outcome key registry.
func LoadOutcomeKeyNamesFromYAML(path string) ([]string, error) {
	b, err := fileutil.ReadFile(path)
	if err != nil {
		return nil, errfmt.Errorf("read pipeline outcome keys registry: %w", err)
	}
	var doc pipelineOutcomeKeysYAML
	if err := yaml.Unmarshal(b, &doc); err != nil {
		return nil, errfmt.Errorf("parse %s: %w", path, err)
	}
	if doc.SchemaVersion != 1 {
		return nil, errfmt.Errorf("%s: unsupported schema_version %d (want 1)", path, doc.SchemaVersion)
	}
	if len(doc.Keys) == 0 {
		return nil, errfmt.Errorf("%s: keys list is empty", path)
	}
	seen := make(map[string]struct{}, len(doc.Keys))
	for _, k := range doc.Keys {
		k = strings.TrimSpace(k)
		if k == "" {
			return nil, errfmt.Errorf("%s: empty key entry", path)
		}
		if _, dup := seen[k]; dup {
			return nil, errfmt.Errorf("%s: duplicate key %q", path, k)
		}
		seen[k] = struct{}{}
	}
	out := append([]string(nil), doc.Keys...)
	sort.Strings(out)
	return out, nil
}

// GenerateOutcomeKeysGoSource returns formatted Go source for outcome_keys.go.
func GenerateOutcomeKeysGoSource(registryPath string, names []string) ([]byte, error) {
	if len(names) == 0 {
		return nil, errfmt.Errorf("no outcome key names")
	}
	used := make(map[string]string)
	for _, name := range names {
		suffix := outcomeKeyConstSuffix(name)
		if suffix == "" {
			return nil, errfmt.Errorf("empty const suffix for key %q", name)
		}
		full := "OutcomeKey" + suffix
		if prev, ok := used[full]; ok {
			return nil, errfmt.Errorf("duplicate generated const %s for keys %q and %q", full, prev, name)
		}
		used[full] = name
	}

	var body strings.Builder
	fmt.Fprintf(&body, `package pipeline

// Code generated by %q. DO NOT EDIT BY HAND.
// Registry: %s
// To regenerate:
//   %s

// Stable keys for [Context].Outcome (JSON / observability contract across stages).
const (
`, paths.CLIUsage("system", "generate-pipeline-outcome-keys"), registryPath, paths.CLIUsage("system", "generate-pipeline-outcome-keys"))

	for _, name := range names {
		suffix := outcomeKeyConstSuffix(name)
		fmt.Fprintf(&body, "\tOutcomeKey%s = %q\n", suffix, name)
	}
	body.WriteString(")\n")
	return objects.FormatGeneratedGoSource([]byte(body.String()))
}
