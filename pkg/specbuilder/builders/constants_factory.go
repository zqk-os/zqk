// SpecConstants represents constants generated from an objects.Spec
type SpecConstants struct {
	ontology       string
	packageName    string
	parentOntology string
	fieldNames     []string
	constantNames  map[string]string // field name -> constant name
}

// GetFieldName returns the constant name for a field (e.g., "FieldId" for "id")
func (sc *SpecConstants) GetFieldName(fieldName string) string {
	if name, ok := sc.constantNames[fieldName]; ok {
		return name
	}
	return ""
}

// GetAllFieldNames returns all field name constants as a map of field name -> constant name
func (sc *SpecConstants) GetAllFieldNames() map[string]string {
	result := make(map[string]string, len(sc.constantNames))
	maps.Copy(result, sc.constantNames)
	return result
}

// GetPackage returns the package name where these constants are defined
func (sc *SpecConstants) GetPackage() string {
	return sc.packageName
}

// GetOntology returns the ontology/name of the spec these constants are for
func (sc *SpecConstants) GetOntology() string {
	return sc.ontology
}

// ToGoCode generates the Go code for these constants
func (sc *SpecConstants) ToGoCode() string {
	var buf strings.Builder

	writePackage(&buf, sc.packageName)
	writeSpecConstantsHeader(&buf, sc.ontology, sc.parentOntology, sc.packageName)

	// Only generate const block if there are fields to define
	when.When(func() bool { return len(sc.fieldNames) > 0 }).Then(func() {
		writeFieldConstants(&buf, sc.fieldNames, sc.constantNames)
	}).OrElseWhen(func() bool { return sc.parentOntology != emptyValue }).Then(func() {
		writeAllInheritedComment(&buf, sc.parentOntology, sc.packageName)
	}).OrElse(func() {
		writeNoFieldsComment(&buf)
	}).Run()

	return buf.String()
}

func writePackage(buf *strings.Builder, packageName string) {
	buf.WriteString("// Code generated by zqk-admin system generate-builders. DO NOT EDIT.\n\n")
	fmt.Fprintf(buf, "package %s\n\n", packageName)
}

func writeSpecConstantsHeader(buf *strings.Builder, ontology, parentOntology, packageName string) {
	fmt.Fprintf(buf, "// Field name constants for %s objects\n", ontology)
	buf.WriteString("// These constants are generated from fields defined in THIS spec (not inherited)\n")
	if parentOntology == emptyValue {
		return
	}
	fmt.Fprintf(buf, "// Inherited fields from %s are defined in %s_constants.go (same package)\n", parentOntology, parentOntology)
	fmt.Fprintf(buf, "// All constants are in package %s, so you can access inherited fields via %s.FieldX\n", packageName, packageName)
}

func writeFieldConstants(buf *strings.Builder, fieldNames []string, constantNames map[string]string) {
	buf.WriteString("const (\n")
	for _, fieldName := range fieldNames {
		constantName := constantNames[fieldName]
		fmt.Fprintf(buf, "\t// %s is the field name for %s\n", constantName, fieldName)
		fmt.Fprintf(buf, "\t%s = %q\n", constantName, fieldName)
	}
	buf.WriteString(")\n")
}

func writeAllInheritedComment(buf *strings.Builder, parentOntology, packageName string) {
	fmt.Fprintf(buf, "// No fields defined in this spec (all fields are inherited from %s)\n", parentOntology)
	fmt.Fprintf(buf, "// Inherited fields are accessible via %s.FieldX from %s_constants.go\n", packageName, parentOntology)
}

func writeNoFieldsComment(buf *strings.Builder) {
	buf.WriteString("// No fields defined in this spec\n")
}

func specFileNameForOntology(ontology string) string {
	return ontology + sbcore.FileExtYAML
}

// ConstantsFactory creates constants from object specs
type ConstantsFactory struct {
	packageName        string
	generatedConstants map[string]string   // constant name -> ontology (to detect conflicts)
	specLoader         *objects.SpecLoader // optional: when set, use instead of global (avoids wrong/empty specsDir in generate-builders)
}

// NewConstantsFactory creates a new constants factory (uses global SpecLoader when loading specs)
func NewConstantsFactory(packageName string) *ConstantsFactory {
	return &ConstantsFactory{
		packageName:        packageName,
		generatedConstants: make(map[string]string),
		specLoader:         nil,
	}
}

// NewConstantsFactoryWithSpecLoader creates a constants factory that uses the given SpecLoader
// instead of the global one. Use this from generate-builders so spec loading uses the same
// specsDir and avoids deep recursion / hang from the global loader (see GENERATE_BUILDERS_SAMPLE_ANALYSIS.md).
func NewConstantsFactoryWithSpecLoader(packageName string, specLoader *objects.SpecLoader) *ConstantsFactory {
	return &ConstantsFactory{
		packageName:        packageName,
		generatedConstants: make(map[string]string),
		specLoader:         specLoader,
	}
}

// ReserveConstantsFromDir records constants already declared by sibling specs.
// This lets single-spec generation namespace collisions without regenerating the
// entire version package. The target ontology is excluded because its constants
// file is about to be replaced.
func (cf *ConstantsFactory) ReserveConstantsFromDir(dir, targetOntology string) error {
	entries, err := fileutil.ReadDir(dir)
	if err != nil {
		if fileutil.IsNotExist(err) {
			return nil
		}
		return errfmt.Newf("read constants directory").Wrap(err)
	}
	targetFile := targetOntology + "_constants.go"
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || name == targetFile || !strings.HasSuffix(name, "_constants.go") {
			continue
		}
		path := filepath.Join(dir, name)
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return errfmt.Newf("parse constants file %s", path).Wrap(err)
		}
		ontology := strings.TrimSuffix(name, "_constants.go")
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.CONST {
				continue
			}
			for _, spec := range gen.Specs {
				value, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for _, ident := range value.Names {
					cf.generatedConstants[ident.Name] = ontology
				}
			}
		}
	}
	return nil
}

// CreateConstants creates constants from a spec
// Only generates constants for fields defined in THIS spec (not inherited)
func (cf *ConstantsFactory) CreateConstants(spec *objects.Spec, ontology string) (sbcore.Constants, error) {
	// Prefer injected loader (e.g. from generate-builders) so we use the correct specsDir
	specLoader := cf.specLoader
	if specLoader == nil {
		specLoader = objects.GetGlobalSpecLoader()
	}
	var currentSpec *objects.Spec
	setFromSpec := func() {
		currentSpec = spec
		if currentSpec != nil && currentSpec.ResolvedFields == nil && currentSpec.Fields != nil {
			currentSpec.ResolvedFields = make(map[string]any)
			maps.Copy(currentSpec.ResolvedFields, currentSpec.Fields)
		}
	}
	when.When(func() bool { return specLoader != nil }).Then(func() {
		loadedSpec, err := specLoader.LoadSpecWithInheritance(specFileNameForOntology(ontology))
		when.When(func() bool { return err == nil && loadedSpec != nil }).Then(func() {
			currentSpec = loadedSpec
		}).OrElse(setFromSpec).Run()
	}).OrElse(setFromSpec).Run()

	// Get parent spec's ResolvedFields to determine which fields are inherited
	var parentResolvedFields map[string]bool
	var parentOntology string
	if currentSpec.Extends != emptyValue && currentSpec.Extends != "null" {
		parentOntology = currentSpec.Extends
		if specLoader != nil {
			parentFile := specFileNameForOntology(parentOntology)
			parentSpec, err := specLoader.LoadSpecWithInheritance(parentFile)
			if err == nil && parentSpec != nil {
				parentResolvedFields = make(map[string]bool)
				if parentSpec.ResolvedFields != nil {
					for fieldName := range parentSpec.ResolvedFields {
						parentResolvedFields[fieldName] = true
					}
				}
			}
		}
	}

	// Only generate constants for fields defined in THIS spec (not inherited)
	// We use spec.Fields (not ResolvedFields) because we only want fields explicitly in the YAML
	fieldNames := make([]string, 0)
	constantNames := make(map[string]string)

	if spec.Fields != nil {
		for fieldName := range spec.Fields {
			// Skip if this field is inherited from parent (exists in parent's ResolvedFields)
			if parentResolvedFields != nil && parentResolvedFields[fieldName] {
				continue
			}
			// This field is defined in this spec (not inherited)
			constantName := "Field" + toCamelCase(fieldName)

			// Check for conflicts with already-generated constants
			if existingOntology, exists := cf.generatedConstants[constantName]; exists && existingOntology != ontology {
				// Namespace by ontology to avoid conflict
				ontologyPrefix := toCamelCase(ontology)
				constantName = ontologyPrefix + constantName
			}

			// Track this constant
			cf.generatedConstants[constantName] = ontology
			fieldNames = append(fieldNames, fieldName)
			constantNames[fieldName] = constantName
		}
		sort.Strings(fieldNames)
	}

	return &SpecConstants{
		ontology:       ontology,
		packageName:    cf.packageName,
		parentOntology: parentOntology,
		fieldNames:     fieldNames,
		constantNames:  constantNames,
	}, nil
}
