// BLI-STARTER-COMMUNITY-057 / PRI-STARTER-COMMUNITY-057 coverage elevation
package drifthotspots

import (
	"path/filepath"
	"testing"

	"github.com/zqk-os/zqk/pkg/paths"
	fileutil "github.com/zqk-os/zqk/pkg/utils/fileutil"
)

func TestExtraFieldKeyScanAndWalk(t *testing.T) {
	if _, err := LoadFieldKeyWireToConstName(nil); err == nil {
		t.Fatal("empty field keys")
	}
	if _, err := LoadFieldKeyWireToConstName([]byte("FieldKeyID = \"id\"\nFieldKeyID2 = \"id\"\n")); err == nil {
		t.Fatal("duplicate wire")
	}
	m, err := LoadFieldKeyWireToConstName([]byte("FieldKeyID = \"id\"\nFieldKeyKind = \"kind\"\n"))
	if err != nil || m["id"] != "FieldKeyID" {
		t.Fatalf("parse: %#v %v", m, err)
	}

	if _, err := LoadFieldKeyWireToConstFromModuleRoot(t.TempDir()); err == nil {
		t.Fatal("missing module field_keys")
	}
	if _, err := LoadFieldKeyWireToConstFromModule("/no/such/start"); err == nil {
		t.Fatal("missing module root")
	}
	mod, err := LoadFieldKeyWireToConstFromModule(".")
	if err != nil || len(mod) == 0 {
		t.Fatalf("from module: %v", err)
	}

	for _, p := range []string{
		"readme.md",
		"scripts/x.go",
		"pkg/objects/field_keys.go",
		"pkg/specbuilder/bldr_instance_v1/x.go",
		"pkg/specbuilder/bldr_v2/x.go",
		"pkg/specbuilder/builders/x.go",
		"pkg/specbuilder/trait_builders/x.go",
		"pkg/cli/foo.go",
		"cmd/zqk/main.go",
		"internal/cli/x.go",
	} {
		_ = ShouldScanFieldKeyLiteralPath(p)
	}

	if !IsConstantBarrelPath("lock_op_names.go") || IsConstantBarrelPath("other.go") {
		t.Fatal("barrel")
	}
	if !IsConstantBarrelPath("pkg/specbuilder/bldr_v2/foo_constants.go") {
		t.Fatal("bldr constants")
	}
	if !IsDataCatalogPath("x_test_helper.go") || IsDataCatalogPath("plain.go") {
		t.Fatal("catalog helper")
	}
	if !IsDataCatalogPath("pkg/objects/kind_mappings.go") {
		t.Fatal("kind mappings")
	}

	_ = isGeneratedGoFile("foo.go")
	_ = isGeneratedSource([]byte("// Code generated by x; DO NOT EDIT.\npackage p\n"))
	_ = isGeneratedSource([]byte("package p\n"))
	_ = riskRank("high")
	_ = riskRank("medium")
	_ = riskRank("low")
	_ = riskRank("nope")
	_ = minRiskFloorRank("")
	_ = minRiskFloorRank("HIGH")
	_ = minRiskFloorRank("medium")
	_ = minRiskFloorRank("low")

	src := []byte("package demo\nfunc f() { _ = map[string]any{\"id\": 1} }\n")
	_, n, err := FixFieldKeyLiteralsInFile("pkg/demo/x.go", src, m, "demo")
	if err != nil {
		t.Fatal(err)
	}
	_ = n
	if _, _, err := FixFieldKeyLiteralsInFile("x.go", []byte("not go"), m, ""); err == nil {
		t.Fatal("parse error")
	}
	_ = replacementIdent("objects", "FieldKeyID")
	_ = replacementIdent("other", "FieldKeyID")

	if _, err := WalkAndFixFieldKeyLiterals(WalkFieldKeyFixConfig{}); err == nil {
		t.Fatal("empty repo")
	}
	tmp := t.TempDir()
	fk := filepath.Join(tmp, "field_keys.go")
	if err := fileutil.WriteFile(fk, []byte("FieldKeyID = \"id\"\n"), paths.FilePerm644); err != nil {
		t.Fatal(err)
	}
	rel := "pkg/demo/demo.go"
	abs := filepath.Join(tmp, rel)
	if err := fileutil.MkdirAll(filepath.Dir(abs), paths.DirPerm755); err != nil {
		t.Fatal(err)
	}
	if err := fileutil.WriteFile(abs, []byte("package demo\nfunc f() { m := map[string]any{\"id\": 1}; _ = m }\n"), paths.FilePerm644); err != nil {
		t.Fatal(err)
	}
	gen := filepath.Join(tmp, "pkg/demo/gen.go")
	if err := fileutil.WriteFile(gen, []byte("// Code generated by spew. DO NOT EDIT.\npackage demo\n"), paths.FilePerm644); err != nil {
		t.Fatal(err)
	}
	res, err := WalkAndFixFieldKeyLiterals(WalkFieldKeyFixConfig{
		RepoRoot:      tmp,
		FieldKeysPath: fk,
		FilePaths:     []string{"", "readme.md", "pkg/demo/missing.go", rel, "pkg/demo/gen.go", "pkg/demo/demo_test.go"},
		PathPrefixes:  []string{"pkg/demo", ""},
		IncludeTests:  false,
		Write:         true,
	})
	if err != nil {
		t.Fatal(err)
	}
	_ = res.FilesScanned
	_, _ = gitListGoFiles(tmp)
	_, _ = gitListGoFiles(".")
	_ = isSpecbuilderBuilderPath("pkg/specbuilder/builders/x.go")
	_ = isSpecbuilderBuilderPath("pkg/foo.go")
	_, _ = Analyze(Options{
		RootDir:                tmp,
		ExtraKindSet:           map[string]struct{}{"demo": {}},
		MinRisk:                "critical",
		IncludeTests:           true,
		IncludeConstantBarrels: true,
	})
	_, _ = WalkAndFixFieldKeyLiterals(WalkFieldKeyFixConfig{
		RepoRoot:      tmp,
		FieldKeysPath: fk,
		FilePaths:     []string{rel, "pkg/demo/demo_test.go"},
		IncludeTests:  true,
		Write:         false,
	})
	_, _, _ = FixFieldKeyLiteralsInFile(rel, src, m, "objects")
	rep := BuildReport(Options{RootDir: tmp, MinRisk: ""}, []Finding{
		{File: "a.go", Risk: "high", Category: "kind"},
		{File: "a.go", Risk: "low", Category: "kind"},
		{File: "b.go", Risk: "medium", Category: "status"},
	})
	if len(rep.FileSummaries) != 2 {
		t.Fatalf("summaries: %#v", rep.FileSummaries)
	}
}
