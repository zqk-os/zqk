func TestAutoGeneratedFieldsFilter_IsFieldAutoGenerated(t *testing.T) {
	bindFieldRegistryToModuleSpecs(t)
	lifecycleLoader := objects.GetGlobalLifecycleLoader()
	filter := interactive.NewAutoGeneratedFieldsFilter(lifecycleLoader)

	tests := []struct {
		name     string
		kind     string
		field    string
		expected bool
	}{
		{
			name:     "created_at is auto-generated",
			kind:     "criteria",
			field:    "created_at",
			expected: true,
		},
		{
			name:     "created_by is auto-generated",
			kind:     "criteria",
			field:    "created_by",
			expected: true,
		},
		{
			name:     "updated_at is auto-generated",
			kind:     "criteria",
			field:    "updated_at",
			expected: true,
		},
		{
			name:     "updated_by is auto-generated",
			kind:     "criteria",
			field:    "updated_by",
			expected: true,
		},
		{
			name:     "kind is auto-generated",
			kind:     "criteria",
			field:    "kind",
			expected: true,
		},
		{
			name:     "schema_version is auto-generated",
			kind:     "criteria",
			field:    "schema_version",
			expected: true,
		},
		{
			name:     "status is auto-generated (from lifecycle)",
			kind:     "criteria",
			field:    "status",
			expected: true,
		},
		{
			name:     "archived_at is auto-generated",
			kind:     "criteria",
			field:    "archived_at",
			expected: true,
		},
		{
			name:     "archived_by is auto-generated",
			kind:     "criteria",
			field:    "archived_by",
			expected: true,
		},
		{
			name:     "change_log is auto-generated",
			kind:     "criteria",
			field:    "change_log",
			expected: true,
		},
		{
			name:     "title is not auto-generated",
			kind:     "criteria",
			field:    "title",
			expected: false,
		},
		{
			name:     "category is not auto-generated",
			kind:     "criteria",
			field:    "category",
			expected: false,
		},
		{
			name:     "description is not auto-generated",
			kind:     "criteria",
			field:    "description",
			expected: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := filter.IsFieldAutoGenerated(tt.kind, tt.field)
			if result != tt.expected {
				t.Errorf("IsFieldAutoGenerated(%q, %q) = %v, want %v", tt.kind, tt.field, result, tt.expected)
			}
		})
	}
}

func TestAutoGeneratedFieldsFilter_FilterFieldsForCreate(t *testing.T) {
	t.Cleanup(ensureRepoSpecsForFieldRegistry(t))
	requireFieldRegistryReloaded(t)
	fieldRegistry := objects.GetGlobalFieldRegistry()

	lifecycleLoader := objects.GetGlobalLifecycleLoader()
	filter := interactive.NewAutoGeneratedFieldsFilter(lifecycleLoader)

	generator := interactive.NewTemplateGeneratorWithLifecycle(fieldRegistry, lifecycleLoader)

	// Generate template for criteria
	templateWithTokens, err := generator.GenerateTemplateWithTokens("criteria")
	if err != nil {
		t.Fatalf("Failed to generate template: %v", err)
	}

	// Filter fields for CREATE operation
	filteredTemplate, err := filter.FilterFieldsForCreate("criteria", templateWithTokens)
	if err != nil {
		t.Fatalf("Failed to filter fields: %v", err)
	}

	// Verify auto-generated fields are excluded
	autoGeneratedFields := []string{
		"kind",
		"schema_version",
		"created_at",
		"created_by",
		"updated_at",
		"updated_by",
		"status",
		"archived_at",
		"archived_by",
		"change_log",
	}

	for _, fieldName := range autoGeneratedFields {
		if _, exists := filteredTemplate.FieldInfo[fieldName]; exists {
			t.Errorf("Auto-generated field %q should be excluded from CREATE template", fieldName)
		}
		if stringSliceContains(filteredTemplate.RequiredFields, fieldName) {
			t.Errorf("Auto-generated field %q should not be in required fields", fieldName)
		}
		if stringSliceContains(filteredTemplate.Tokens, fieldName) {
			t.Errorf("Auto-generated field %q should not be in tokens", fieldName)
		}
	}

	// Verify user-provided fields are included
	userProvidedFields := []string{"title", "category", "description"}
	for _, fieldName := range userProvidedFields {
		if !stringSliceContains(filteredTemplate.Tokens, fieldName) {
			t.Logf("User-provided field %q not found in tokens (may not be required)", fieldName)
		}
	}

	// Verify at least some fields remain
	if len(filteredTemplate.Tokens) == 0 {
		t.Error("Filtered template should have at least some fields")
	}
	if len(filteredTemplate.FieldInfo) == 0 {
		t.Error("Filtered template should have at least some field info")
	}
}

func TestStreamingTemplateGenerator_FiltersAutoGeneratedFields(t *testing.T) {
	t.Cleanup(ensureRepoSpecsForFieldRegistry(t))
	requireFieldRegistryReloaded(t)
	fieldRegistry := objects.GetGlobalFieldRegistry()

	// Use generator with lifecycle loader (auto-filters)
	generator := interactive.NewTemplateGenerator(fieldRegistry)

	// Generate template for criteria
	templateWithTokens, err := generator.GenerateTemplateWithTokens("criteria")
	if err != nil {
		t.Fatalf("Failed to generate template: %v", err)
	}

	// Verify auto-generated fields are not in tokens
	autoGeneratedFields := []string{
		"kind",
		"schema_version",
		"created_at",
		"created_by",
		"updated_at",
		"updated_by",
		"status",
		"archived_at",
		"archived_by",
		"change_log",
	}

	for _, fieldName := range autoGeneratedFields {
		if stringSliceContains(templateWithTokens.Tokens, fieldName) {
			t.Errorf("Auto-generated field %q should not be in tokens", fieldName)
		}
		if stringSliceContains(templateWithTokens.RequiredFields, fieldName) {
			t.Errorf("Auto-generated field %q should not be in required fields", fieldName)
		}
	}

	// Verify at least some fields remain
	if len(templateWithTokens.Tokens) == 0 {
		t.Error("Template should have at least some fields")
	}

	// Verify user-provided fields are included (if required)
	// title is typically required for criteria
	if !stringSliceContains(templateWithTokens.Tokens, "title") && !stringSliceContains(templateWithTokens.RequiredFields, "title") {
		t.Logf("title field not found (may be optional or filtered)")
	}
}
