import os
import re

enum_dir = 'pkg/specbuilder/bldr_enum_v1'
dirs = sorted([d for d in os.listdir(enum_dir) if os.path.isdir(os.path.join(enum_dir, d))])

for d in dirs:
    path = os.path.join(enum_dir, d)
    go_files = [f for f in os.listdir(path) if f.endswith('.go') and not f.endswith('_test.go')]
    if not go_files:
        continue
    
    pkg_name = d
    consts = []
    types = []
    
    for gf in go_files:
        content = open(os.path.join(path, gf)).read()
        m_pkg = re.search(r'^package\s+([A-Za-z0-9_]+)', content, re.MULTILINE)
        if m_pkg:
            pkg_name = m_pkg.group(1)
        
        # Match type declarations
        for m in re.finditer(r'^type\s+([A-Za-z0-9_]+)\s*(=|\s+string)', content, re.MULTILINE):
            t_name = m.group(1)
            if t_name not in types:
                types.append(t_name)
                
        # Match const declarations
        # In const (...) blocks or single const
        for m in re.finditer(r'^\s*([A-Z][A-Za-z0-9_]*)\s+(?:[A-Za-z0-9_.]+\s+)?=', content, re.MULTILINE):
            c_name = m.group(1)
            if c_name not in consts:
                consts.append(c_name)
                
    test_file_path = os.path.join(path, 'enums_generated_test.go')
    lines = [
        '// Code generated by scripts/generate_enum_tests.py; DO NOT EDIT.',
        '',
        f'package {pkg_name}',
        '',
        'import (',
        '\t"testing"',
        ')',
        '',
        'func TestEnums_Completeness(t *testing.T) {',
    ]
    
    if consts:
        lines.append('\ttests := []struct {')
        lines.append('\t\tname string')
        lines.append('\t\tval  string')
        lines.append('\t}{')
        for c in consts:
            lines.append(f'\t\t{{"{c}", string({c})}},')
        lines.append('\t}')
        lines.append('\tfor _, tt := range tests {')
        lines.append('\t\tif tt.val == "" {')
        lines.append('\t\t\tt.Errorf("constant %s has empty value", tt.name)')
        lines.append('\t\t}')
        lines.append('\t}')
    else:
        # e.g. metrics package with only types
        lines.append('\t// Verify enum types are defined')
        for t in types:
            lines.append(f'\tvar _ {t} = {t}("test")')
        lines.append('\tt.Log("enum types verified")')
        
    lines.append('}\n')
    
    with open(test_file_path, 'w') as f:
        f.write('\n'.join(lines))

print(f'Generated tests for {len(dirs)} enum packages.')
